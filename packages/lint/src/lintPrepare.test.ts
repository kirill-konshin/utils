test('recordSyncedSkills: lists the skills the CLI installed below their own header; syncAgentDirs keeps them', async () => {
    await inTempDir({ '.agents/skills/own/SKILL.md': '' }, async (cwd) => {
        sync(cwd);
        syncRemoteSkill(cwd, 'remote');

        recordSyncedSkills(cwd);
        sync(cwd);

        assert.deepEqual(lines(join(cwd, '.agents/skills/.gitignore')), [
            GITIGNORE_HEADER,
            '/.gitignore',
            GITIGNORE_SYNCED,
            '/remote',
            '',
        ]);
        assert.deepEqual(lines(join(cwd, '.claude/skills/.gitignore')), [
            GITIGNORE_HEADER,
            '/.gitignore',
            '/own',
            GITIGNORE_SYNCED,
            '/remote',
            '',
        ]);
        assert.ok(lstatSync(join(cwd, '.agents/skills/remote/SKILL.md')).isFile());
        assert.equal(readlinkSync(join(cwd, '.claude/skills/remote')), '../../.agents/skills/remote');
    });
});

