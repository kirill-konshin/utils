import assert from 'node:assert/strict';
import {
    lstatSync,
    mkdirSync,
    readdirSync,
    readFileSync,
    readlinkSync,
    realpathSync,
    renameSync,
    symlinkSync,
    writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vite-plus/test';
import { parse } from 'yaml';

import {
    generateAgentsFile,
    installedRules,
    packageEntries,
    readRules,
    readSkills,
    readUserEntries,
    syncAgentDirs,
} from './lintPrepare.js';
import { inTempDir } from './testUtils.js';

const PACKAGE_DIR = fileURLToPath(new URL('..', import.meta.url));
const AGENT_DIRS = ['.agents', '.claude'];
const AUTH_RULE = { file: 'auth.md', name: 'auth', content: '' };
const LINT_REPO_SKILL = { name: 'lint-repo' };
// the generated .gitignore format older versions wrote - the cleanup of their links depends on it
const GITIGNORE_HEADER = '# Generated by @kirill.konshin/lint: symlinks it manages here, your own files stay tracked';

/**
 * Where `link` points, one hop only - a chained link would resolve to another link, not to the entry itself.
 */
const linkTarget = (link: string): string => resolve(realpathSync(dirname(link)), readlinkSync(link));

/**
 * Run the sync the way `lint-prepare` does, with one package rule and skill.
 */
const sync = (cwd: string, entries = packageEntries([AUTH_RULE], [LINT_REPO_SKILL])): void =>
    syncAgentDirs(cwd, entries, readUserEntries(cwd));

const list = (dir: string): string[] => readdirSync(dir).sort();

test('readRules: every shipped rule has a frontmatter description', () => {
    for (const rule of readRules()) {
        assert.ok(rule.description, `${rule.file} has no description`);
    }
});

test('readSkills: every shipped skill has valid YAML frontmatter naming it, with a description', () => {
    const skillsDir = resolve(dirname(fileURLToPath(import.meta.url)), '../skills');
    for (const { name } of readSkills()) {
        const content = readFileSync(join(skillsDir, name, 'SKILL.md'), 'utf8');
        const frontmatter = /^---\n([\s\S]*?)\n---/.exec(content)?.[1];
        assert.ok(frontmatter, `${name}: no frontmatter`);
        // a plain scalar holding `: ` is a nested mapping - agents and IDEs reject the file, Oxfmt does not notice
        const parsed = parse(frontmatter) as { name?: unknown; description?: unknown };
        assert.equal(parsed.name, name, `${name}: frontmatter name`);
        assert.equal(typeof parsed.description, 'string', `${name}: frontmatter description`);
    }
});

test('generateAgentsFile: one plain entry per rule with its description, scope and .agents path, never an @ import', () => {
    const content = generateAgentsFile(
        [
            {
                file: 'monorepo-turbo-nx.md',
                name: 'monorepo-turbo-nx',
                description: 'Monorepo rules',
                paths: ['**/nx.json', '**/turbo.json'],
                content: '',
            },
            { file: 'i18n.md', name: 'i18n', content: '' },
        ],
        null,
    );

    const expected = [
        '# Rules',
        '',
        '- **Monorepo turbo nx** — Monorepo rules; when touching `**/nx.json`, `**/turbo.json`: [.agents/rules/monorepo-turbo-nx.md](.agents/rules/monorepo-turbo-nx.md)',
        '- **I18n**: [.agents/rules/i18n.md](.agents/rules/i18n.md)',
        '',
        '<!--VITE PLUS START-->',
        '<!--VITE PLUS END-->',
        '',
        '---',
    ].join('\n');

    assert.ok(content.includes(expected), content);
    assert.ok(!content.includes('@.agents'), content);
});

test('generateAgentsFile: an empty anchor for each tool section above the custom section - the tool run next fills it', () => {
    const content = generateAgentsFile([], '# Mine');
    assert.ok(content.includes('<!--VITE PLUS START-->\n<!--VITE PLUS END-->'), content);
    assert.ok(content.indexOf('<!--VITE PLUS START-->') < content.indexOf('# Custom Rules'), content);
    assert.ok(content.trimEnd().endsWith('# Mine'), content);
});

test('syncAgentDirs: real agent dirs, a rule file and a skill folder each linked straight to the package, from a symlinked cwd too', async () => {
    await inTempDir({ 'real/nested/project/.keep': '' }, async (dir) => {
        // the link sits at a different depth than its target, paths computed lexically from it would dangle
        const cwd = join(dir, 'link');
        symlinkSync(join(dir, 'real/nested/project'), cwd);

        sync(cwd);

        for (const agentDir of AGENT_DIRS) {
            for (const kind of ['rules', 'skills']) {
                assert.ok(lstatSync(join(cwd, agentDir, kind)).isDirectory());
            }

            assert.equal(
                linkTarget(join(cwd, agentDir, 'rules/auth.md')),
                realpathSync(join(PACKAGE_DIR, 'rules/auth.md')),
            );
            assert.equal(
                linkTarget(join(cwd, agentDir, 'skills/lint-repo')),
                realpathSync(join(PACKAGE_DIR, 'skills/lint-repo')),
            );
        }
    });
});

test('syncAgentDirs: every shipped skill arrives in every agent dir as one folder link', async () => {
    const skills = readSkills();

    await inTempDir({ '.keep': '' }, async (cwd) => {
        sync(cwd, packageEntries([], skills));

        for (const { name } of skills) {
            for (const agentDir of AGENT_DIRS) {
                const skill = join(cwd, agentDir, 'skills', name);
                assert.equal(linkTarget(skill), realpathSync(join(PACKAGE_DIR, 'skills', name)), skill);
                assert.ok(lstatSync(join(skill, 'SKILL.md')).isFile(), `${skill}/SKILL.md`);
            }
        }
    });
});

test("syncAgentDirs: mirrors the user's own top-level .agents entries into .claude, a user entry wins over the package one", async () => {
    const own = ['rules/auth.md', 'rules/local.md', 'skills/own/SKILL.md', 'skills/lint-repo/SKILL.md'];

    await inTempDir(Object.fromEntries(own.map((file) => [`.agents/${file}`, file])), async (cwd) => {
        sync(cwd);

        assert.equal(readFileSync(join(cwd, '.agents/rules/auth.md'), 'utf8'), 'rules/auth.md');
        assert.ok(lstatSync(join(cwd, '.agents/skills/lint-repo')).isDirectory(), 'the package skill is not installed');

        for (const entry of ['rules/auth.md', 'rules/local.md', 'skills/own', 'skills/lint-repo']) {
            assert.equal(linkTarget(join(cwd, '.claude', entry)), join(realpathSync(cwd), '.agents', entry));
        }
    });
});

test("syncAgentDirs: removes dead links and links it no longer places, keeps the user's entries and links", async () => {
    await inTempDir({ '.agents/rules/old.md': '', '.claude/rules/own.md': '' }, async (cwd) => {
        sync(cwd);

        renameSync(join(cwd, '.agents/rules/old.md'), join(cwd, '.agents/rules/new.md'));
        symlinkSync('missing.md', join(cwd, '.claude/rules/dead.md'));
        symlinkSync('missing', join(cwd, '.claude/skills/gone'));
        symlinkSync(join(cwd, '.agents/rules/new.md'), join(cwd, '.claude/rules/alias.md'));

        // the package dropped its rule and skill
        sync(cwd, packageEntries([], []));

        assert.deepEqual(list(join(cwd, '.agents/rules')), ['new.md']);
        assert.deepEqual(list(join(cwd, '.claude/rules')), ['.gitignore', 'alias.md', 'new.md', 'own.md']);
        assert.deepEqual(list(join(cwd, '.agents/skills')), []);
        assert.deepEqual(list(join(cwd, '.claude/skills')), []);
    });
});

test('syncAgentDirs: cleans up what older versions placed - per-file skill links, commands - and never touches .codex', async () => {
    await inTempDir({ '.codex/rules/default.rules': '', '.agents/commands/mine.md': '' }, async (cwd) => {
        const shipped = join(PACKAGE_DIR, 'skills/lint-repo/SKILL.md');
        const legacy = (dir: string, links: Record<string, string>): void => {
            for (const [link, target] of Object.entries(links)) {
                mkdirSync(dirname(join(cwd, dir, link)), { recursive: true });
                symlinkSync(target, join(cwd, dir, link));
            }
            writeFileSync(
                join(cwd, dir, '.gitignore'),
                [GITIGNORE_HEADER, ...Object.keys(links).map((l) => `/${l}`)].join('\n'),
            );
        };

        legacy('.claude/skills', { 'lint-repo/SKILL.md': shipped });
        legacy('.claude/commands', { 'mine.md': join(cwd, '.agents/commands/mine.md') });
        legacy('.codex/skills', { 'lint-repo/SKILL.md': shipped });

        sync(cwd);

        assert.equal(
            linkTarget(join(cwd, '.claude/skills/lint-repo')),
            realpathSync(join(PACKAGE_DIR, 'skills/lint-repo')),
        );
        assert.deepEqual(list(join(cwd, '.codex')), ['rules', 'skills']);
        assert.deepEqual(list(join(cwd, '.codex/rules')), ['default.rules']);
        assert.ok(lstatSync(join(cwd, '.codex/skills/lint-repo/SKILL.md')).isSymbolicLink(), '.codex is not touched');
        assert.deepEqual(list(join(cwd, '.agents/commands')), ['mine.md']);
        assert.ok(!lstatSync(join(cwd, '.claude/commands'), { throwIfNoEntry: false }), '.claude/commands removed');
    });
});

test('syncAgentDirs: never writes over a real entry or through a linked directory', async () => {
    await inTempDir({ '.claude/rules/auth.md': 'mine', 'shared/.keep': '' }, async (cwd) => {
        symlinkSync(join(cwd, 'shared'), join(cwd, '.claude/skills'));

        sync(cwd);

        assert.equal(readFileSync(join(cwd, '.claude/rules/auth.md'), 'utf8'), 'mine');
        assert.deepEqual(list(join(cwd, 'shared')), ['.keep']);
    });
});

test('syncAgentDirs: .gitignore lists only the links, a .gitignore of the user is left alone', async () => {
    await inTempDir(
        { '.agents/rules/local.md': '', '.agents/skills/own/SKILL.md': '', '.claude/skills/.gitignore': 'mine\n' },
        async (cwd) => {
            sync(cwd);

            const entries = (dir: string): string[] =>
                readFileSync(join(cwd, dir, '.gitignore'), 'utf8')
                    .split('\n')
                    .slice(1);

            assert.deepEqual(entries('.agents/rules'), ['/.gitignore', '/auth.md', '']);
            assert.deepEqual(entries('.claude/rules'), ['/.gitignore', '/auth.md', '/local.md', '']);
            assert.deepEqual(entries('.agents/skills'), ['/.gitignore', '/lint-repo', '']);
            assert.equal(readFileSync(join(cwd, '.claude/skills/.gitignore'), 'utf8'), 'mine\n');
        },
    );
});

test("installedRules: the user's .agents rule files join the package ones, winning on the same file", async () => {
    await inTempDir(
        {
            '.agents/rules/auth.md': '---\ndescription: Mine\n---\n',
            '.agents/rules/zeta.md': '',
            '.agents/rules/team/x.md': '',
        },
        async (cwd) => {
            const packageRules = [
                { ...AUTH_RULE, description: 'Package' },
                { file: 'i18n.md', name: 'i18n', content: '' },
            ];

            assert.deepEqual(
                installedRules(packageRules, readUserEntries(cwd)).map(({ file, description }) => [file, description]),
                [
                    ['auth.md', 'Mine'],
                    ['i18n.md', undefined],
                    ['zeta.md', undefined],
                ],
            );
        },
    );
});
