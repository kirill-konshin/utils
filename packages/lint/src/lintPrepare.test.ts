test('syncAgentDirs: .gitignore lists only the links, a .gitignore of the user is left alone', async () => {
    await inTempDir(
        { '.agents/rules/local.md': '', '.agents/skills/own/SKILL.md': '', '.claude/skills/.gitignore': 'mine\n' },
        async (cwd) => {
            sync(cwd);

            const entries = (dir: string): string[] =>
                readFileSync(join(cwd, dir, '.gitignore'), 'utf8')
                    .split('\n')
                    .slice(1);

            assert.deepEqual(entries('.agents/rules'), ['/.gitignore', '/auth.md', '']);
            assert.deepEqual(entries('.claude/rules'), ['/.gitignore', '/auth.md', '/local.md', '']);
            assert.deepEqual(list(join(cwd, '.agents/skills')), ['own'], 'no links, no .gitignore');
            assert.equal(readFileSync(join(cwd, '.claude/skills/.gitignore'), 'utf8'), 'mine\n');
        },
    );
});

