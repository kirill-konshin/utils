test('planSkills: npm sources become sync exclusions, enabled git sources become skills add work', () => {
    const plan = planSkills(
        {
            '@kirill.konshin/lint': { skills: { 'lint-electron': false } },
            'off-pkg': false,
            'picky-pkg': { skills: { a: true } },
            'vercel-labs/agent-skills': { ref: 'abc', skills: { x: true, y: false } },
            'shadcn/ui': true,
            'heroui-inc/heroui': { skills: { 'heroui-native': false } },
            'gone/repo': false,
        },
        (packageName) => (packageName === 'picky-pkg' ? ['a', 'b', 'c'] : []),
    );

    assert.deepEqual(plan.syncExclude, ['@kirill.konshin/lint#lint-electron', 'off-pkg', 'picky-pkg#b', 'picky-pkg#c']);
    assert.deepEqual(plan.remote, [
        { source: 'vercel-labs/agent-skills', ref: 'abc', skills: ['x'], exclude: ['y'] },
        { source: 'shadcn/ui', ref: undefined, skills: '*', exclude: [] },
        { source: 'heroui-inc/heroui', ref: undefined, skills: '*', exclude: ['heroui-native'] },
    ]);
});

