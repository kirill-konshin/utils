const PACKAGE_DIR = fileURLToPath(new URL('..', import.meta.url));
const AGENT_DIRS = ['.agents', '.claude'];
const AUTH_RULE = { file: 'auth.md', name: 'auth', content: '' };
// the generated .gitignore format older versions wrote - the cleanup of their links depends on it
const GITIGNORE_HEADER = '# Generated by @kirill.konshin/lint: symlinks it manages here, your own files stay tracked';
const GITIGNORE_SYNCED = '# Installed by the skills CLI (skills-lock.json)';

/**
 * Where `link` points, one hop only - a chained link would resolve to another link, not to the entry itself.
 */
const linkTarget = (link: string): string => resolve(realpathSync(dirname(link)), readlinkSync(link));

/**
 * Run the sync the way `lint-prepare` does, with one package rule.
 */
const sync = (cwd: string, entries = packageEntries([AUTH_RULE])): void =>
    syncAgentDirs(cwd, entries, readUserEntries(cwd));

/**
 * What the `skills` CLI leaves behind for a remote skill: a real folder in `.agents/skills`, a `.claude/skills` link to
 * it, and its lock entry.
 */
const syncRemoteSkill = (cwd: string, name: string): void => {
    mkdirSync(join(cwd, '.agents/skills', name), { recursive: true });
    writeFileSync(join(cwd, '.agents/skills', name, 'SKILL.md'), '');
    mkdirSync(join(cwd, '.claude/skills'), { recursive: true });
    symlinkSync(join('../../.agents/skills', name), join(cwd, '.claude/skills', name));
    writeFileSync(join(cwd, 'skills-lock.json'), JSON.stringify({ version: 1, skills: { [name]: {} } }));
};

const list = (dir: string): string[] => readdirSync(dir).sort();
const lines = (file: string): string[] => readFileSync(file, 'utf8').split('\n');

