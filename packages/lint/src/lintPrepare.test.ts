test('syncAgentDirs: real agent dirs, a rule file linked straight to the package, from a symlinked cwd too', async () => {
    await inTempDir({ 'real/nested/project/.keep': '' }, async (dir) => {
        // the link sits at a different depth than its target, paths computed lexically from it would dangle
        const cwd = join(dir, 'link');
        symlinkSync(join(dir, 'real/nested/project'), cwd);

        sync(cwd);

        for (const agentDir of AGENT_DIRS) {
            for (const kind of ['rules', 'skills']) {
                assert.ok(lstatSync(join(cwd, agentDir, kind)).isDirectory());
            }

            assert.equal(
                linkTarget(join(cwd, agentDir, 'rules/auth.md')),
                realpathSync(join(PACKAGE_DIR, 'rules/auth.md')),
            );
            assert.deepEqual(list(join(cwd, agentDir, 'skills')), [], 'package skills are for the skills CLI');
        }
    });
});

test('syncAgentDirs: removes the package skill links older versions placed, so the skills CLI can place its own', async () => {
    await inTempDir({ '.keep': '' }, async (cwd) => {
        for (const agentDir of AGENT_DIRS) {
            mkdirSync(join(cwd, agentDir, 'skills'), { recursive: true });
            symlinkSync(join(PACKAGE_DIR, 'skills/lint-repo'), join(cwd, agentDir, 'skills/lint-repo'));
            writeFileSync(
                join(cwd, agentDir, 'skills/.gitignore'),
                [GITIGNORE_HEADER, '/.gitignore', '/lint-repo'].join('\n'),
            );
        }

        sync(cwd);

        for (const agentDir of AGENT_DIRS) assert.deepEqual(list(join(cwd, agentDir, 'skills')), []);
    });
});

test("syncAgentDirs: mirrors the user's own top-level .agents entries into .claude, a user entry wins over the package one", async () => {
    const own = ['rules/auth.md', 'rules/local.md', 'skills/own/SKILL.md', 'skills/lint-repo/SKILL.md'];

    await inTempDir(Object.fromEntries(own.map((file) => [`.agents/${file}`, file])), async (cwd) => {
        sync(cwd);

        assert.equal(readFileSync(join(cwd, '.agents/rules/auth.md'), 'utf8'), 'rules/auth.md');

        for (const entry of ['rules/auth.md', 'rules/local.md', 'skills/own', 'skills/lint-repo']) {
            assert.equal(linkTarget(join(cwd, '.claude', entry)), join(realpathSync(cwd), '.agents', entry));
        }
    });
});

test("syncAgentDirs: removes dead links and links it no longer places, keeps the user's entries and links", async () => {
    await inTempDir({ '.agents/rules/old.md': '', '.claude/rules/own.md': '' }, async (cwd) => {
        sync(cwd);

        renameSync(join(cwd, '.agents/rules/old.md'), join(cwd, '.agents/rules/new.md'));
        symlinkSync('missing.md', join(cwd, '.claude/rules/dead.md'));
        symlinkSync('missing', join(cwd, '.claude/skills/gone'));
        symlinkSync(join(cwd, '.agents/rules/new.md'), join(cwd, '.claude/rules/alias.md'));

        // the package dropped its rule
        sync(cwd, packageEntries([]));

        assert.deepEqual(list(join(cwd, '.agents/rules')), ['new.md']);
        assert.deepEqual(list(join(cwd, '.claude/rules')), ['.gitignore', 'alias.md', 'new.md', 'own.md']);
        assert.deepEqual(list(join(cwd, '.agents/skills')), []);
        assert.deepEqual(list(join(cwd, '.claude/skills')), []);
    });
});

test('syncAgentDirs: cleans up what older versions placed - per-file skill links, commands - and never touches .codex', async () => {
    await inTempDir({ '.codex/rules/default.rules': '', '.agents/commands/mine.md': '' }, async (cwd) => {
        const shipped = join(PACKAGE_DIR, 'skills/lint-repo/SKILL.md');
        const legacy = (dir: string, links: Record<string, string>): void => {
            for (const [link, target] of Object.entries(links)) {
                mkdirSync(dirname(join(cwd, dir, link)), { recursive: true });
                symlinkSync(target, join(cwd, dir, link));
            }
            writeFileSync(
                join(cwd, dir, '.gitignore'),
                [GITIGNORE_HEADER, ...Object.keys(links).map((l) => `/${l}`)].join('\n'),
            );
        };

        legacy('.claude/skills', { 'lint-repo/SKILL.md': shipped });
        legacy('.claude/commands', { 'mine.md': join(cwd, '.agents/commands/mine.md') });
        legacy('.codex/skills', { 'lint-repo/SKILL.md': shipped });

        sync(cwd);

        assert.deepEqual(list(join(cwd, '.claude/skills')), []);
        assert.deepEqual(list(join(cwd, '.codex')), ['rules', 'skills']);
        assert.deepEqual(list(join(cwd, '.codex/rules')), ['default.rules']);
        assert.ok(lstatSync(join(cwd, '.codex/skills/lint-repo/SKILL.md')).isSymbolicLink(), '.codex is not touched');
        assert.deepEqual(list(join(cwd, '.agents/commands')), ['mine.md']);
        assert.ok(!lstatSync(join(cwd, '.claude/commands'), { throwIfNoEntry: false }), '.claude/commands removed');
    });
});

