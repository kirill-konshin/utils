const lstat = (file: string): fs.Stats | undefined => fs.lstatSync(file, { throwIfNoEntry: false });

/**
 * `monorepo-turbo-nx` -> `Monorepo turbo nx`
 */
const toTitle = (name: string): string => {
    const title = name.replaceAll('-', ' ');
    return title.charAt(0).toUpperCase() + title.slice(1);
};

/**
 * A rule's YAML frontmatter, empty when it has none.
 */
const readFrontmatter = (content: string): Record<string, unknown> => {
    const frontmatter = FRONTMATTER.exec(content)?.[1];
    const parsed: unknown = frontmatter ? parse(frontmatter) : undefined;
    return parsed && typeof parsed === 'object' ? (parsed as Record<string, unknown>) : {};
};

/**
 * A frontmatter field read as a list of strings: one string, or a list of them.
 */
const stringList = (value: unknown): string[] | undefined => {
    const items = typeof value === 'string' ? [value] : Array.isArray(value) ? value : [];
    const strings = items.filter((item): item is string => typeof item === 'string' && item.trim() !== '');
    return strings.length ? strings : undefined;
};

/**
 * `file` is the path inside a rules dir, e.g. `auth.md` or `frontend/react.md`.
 */
const toRule = (file: string, content: string): Rule => {
    const { description, paths } = readFrontmatter(content);

    return {
        file,
        name: path.posix.basename(file, '.md'),
        description: typeof description === 'string' ? description.trim() : undefined,
        paths: stringList(paths),
        content,
    };
};

/**
 * Dead symlinks under `dir`, walking real directories only.
 */
function findDeadLinks(dir: string): string[] {
    return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
        const entryPath = path.join(dir, entry.name);

        if (entry.isDirectory()) return findDeadLinks(entryPath);
        return entry.isSymbolicLink() && !fs.existsSync(entryPath) ? [entryPath] : [];
    });
}

/**
 * Remove `link` and the directories it leaves empty, up to `root`.
 */
function removeLink(link: string, root: string): void {
    fs.unlinkSync(link);

    for (let dir = path.dirname(link); dir !== root && !fs.readdirSync(dir).length; dir = path.dirname(dir)) {
        fs.rmdirSync(dir);
    }
}

/**
 * mkdir -p `dir` (relative to cwd, starting with an agent dir, which itself may be a link) without going through
 * links below it: false when a part is a symlink or a file - those are the user's, nothing is written through them.
 */
function ensureRealDir(cwd: string, dir: string): boolean {
    const [agentDir, ...parts] = dir.split(path.sep);
    let current = path.join(cwd, agentDir);

    fs.mkdirSync(current, { recursive: true });

    for (const part of parts) {
        current = path.join(current, part);
        const stat = lstat(current);

        if (!stat) fs.mkdirSync(current);
        else if (!stat.isDirectory()) return false;
    }

    return true;
}

/**
 * Point `link` (relative to cwd) at `target`, unless the spot is the user's: a real file there, or a linked
 * directory on the way. Returns whether the link is in place.
 */
function placeLink(cwd: string, link: string, target: string): boolean {
    const linkPath = path.join(cwd, link);

    if (!ensureRealDir(cwd, path.dirname(link))) {
        console.log(`Skipped ${link}: ${path.dirname(link)} is not a real directory`);
        return false;
    }

    const stat = lstat(linkPath);

    if (stat && !stat.isSymbolicLink()) {
        console.log(`Kept ${link}: not a symlink`);
        return false;
    }

    // relative between REAL locations: cwd and the package (workspaces, yalc, pnpm store) may be reached through
    // symlinks, and a path computed between a symlinked and a real location dangles
    const text = path.relative(fs.realpathSync(path.dirname(linkPath)), target);

    if (stat && fs.readlinkSync(linkPath) === text) return true;
    if (stat) fs.unlinkSync(linkPath);
    fs.symlinkSync(text, linkPath);

    return true;
}

/**
 * Links listed in a `.gitignore` this tool generated - it doubles as the record of what to clean up next time.
 */
function readManifest(gitignore: string): string[] {
    return readGitignoreBlocks(gitignore).links;
}

/**
 * The two lists of a `.gitignore` this tool generated: its own links, and the skills the `skills` CLI installed.
 */
function readGitignoreBlocks(gitignore: string): { links: string[]; synced: string[] } {
    const content = fs.existsSync(gitignore) ? fs.readFileSync(gitignore, 'utf-8') : '';

    if (!content.startsWith(GITIGNORE_HEADER)) return { links: [], synced: [] };

    const [own, synced = ''] = content.split(GITIGNORE_SYNCED);
    const entries = (block: string) =>
        block
            .split('\n')
            .filter((line) => line.startsWith('/') && line !== `/${GITIGNORE}`)
            .map((line) => path.normalize(line.slice(1)));

    return { links: entries(own), synced: entries(synced) };
}

/**
 * Write the `.gitignore` listing `links`, then the `synced` skills below their own header (remove it when both are
 * empty), unless the user owns that file.
 */
function writeManifest(gitignore: string, links: string[], synced: string[] = []): void {
    const exists = fs.existsSync(gitignore);

    if (exists && !fs.readFileSync(gitignore, 'utf-8').startsWith(GITIGNORE_HEADER)) return;

    if (!links.length && !synced.length) {
        if (exists) fs.unlinkSync(gitignore);
        return;
    }

    const toEntries = (names: string[]) => names.map((name) => `/${name.split(path.sep).join('/')}`).sort();
    const syncedBlock = synced.length ? [GITIGNORE_SYNCED, ...toEntries(synced)] : [];

    fs.writeFileSync(
        gitignore,
        [GITIGNORE_HEADER, `/${GITIGNORE}`, ...toEntries(links), ...syncedBlock, ''].join('\n'),
    );
}

/**
 * Top-level names this tool linked into a directory on a previous run, from its generated `.gitignore`.
 */
const manifestNames = (dir: string): Set<string> =>
    new Set(readManifest(path.join(dir, GITIGNORE)).map((link) => link.split(path.sep)[0]));

/**
 * Remove the links listed in a generated `.gitignore` of a directory this tool no longer manages, then the
 * `.gitignore` and the directory itself when nothing else is left.
 */
function cleanUpLegacyDir(cwd: string, dir: string): void {
    const root = path.join(cwd, dir);

    if (!lstat(root)?.isDirectory()) return;

    for (const link of [
        ...findDeadLinks(root),
        ...readManifest(path.join(root, GITIGNORE)).map((l) => path.join(root, l)),
    ]) {
        if (lstat(link)?.isSymbolicLink()) removeLink(link, root);
    }

    writeManifest(path.join(root, GITIGNORE), []);

    // commands are skills now - an own command left behind is the user's to move
    for (const entry of fs.readdirSync(root).filter((name) => !name.startsWith('.'))) {
        console.log(
            `Kept ${path.join(dir, entry)}: commands are no longer synced, make it a skill in ${CANONICAL_AGENT_DIR}/skills`,
        );
    }

    if (!fs.readdirSync(root).length) fs.rmdirSync(root);
}

/**
 * Links to place, keyed by their path relative to cwd: package entries into every agent dir, the user's own `.agents`
 * entries into the mirrors. A user entry wins over the package entry of the same name.
 */
function plannedLinks(
    cwd: string,
    packageEntries: Map<string, string>,
    userEntries: Map<string, string>,
): Map<string, string> {
    const canonicalDir = path.join(fs.realpathSync(cwd), CANONICAL_AGENT_DIR);
    const links = new Map<string, string>();

    for (const [entry, source] of packageEntries) {
        if (userEntries.has(entry)) {
            console.log(`${path.join(CANONICAL_AGENT_DIR, entry)} is the user's, the package one is not installed`);
            continue;
        }

        for (const dir of AGENT_DIRS) links.set(path.join(dir, entry), fs.realpathSync(source));
    }

    for (const entry of userEntries.keys()) {
        for (const dir of MIRROR_AGENT_DIRS) links.set(path.join(dir, entry), path.join(canonicalDir, entry));
    }

    return links;
}

/**
 * Read all markdown files from the package rules directory.
 */
export function readRules(): Rule[] {
    const rules: Rule[] = [];

    if (!fs.existsSync(RULES_DIR)) {
        console.error(`Rules directory not found: ${RULES_DIR}`);
        process.exit(1);
    }

    const files = fs
        .readdirSync(RULES_DIR)
        .filter((f) => f.endsWith('.md'))
        .sort();

    for (const file of files) {
        const filePath = path.join(RULES_DIR, file);
        rules.push(toRule(file, fs.readFileSync(filePath, 'utf-8')));
    }

    return rules;
}

/**
 * Read the package skills directory: every directory holding a `SKILL.md` is a skill named after the directory,
 * shipped with all its files (scripts, references, ...).
 */
export function readSkills(): Skill[] {
    if (!fs.existsSync(SKILLS_DIR)) return [];

    return fs
        .readdirSync(SKILLS_DIR, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(SKILLS_DIR, entry.name, 'SKILL.md')))
        .map((entry) => ({ name: entry.name }))
        .sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * Package entries to link, keyed by their path inside an agent dir: every rule file as `rules/<file>`. Package skills
 * are not linked here: the `skills` CLI installs them (runSkillsSync()).
 */
export function packageEntries(rules: Rule[]): Map<string, string> {
    const entries = new Map<string, string>();

    for (const rule of rules) {
        entries.set(path.join('rules', rule.file), path.join(RULES_DIR, rule.file));
    }

    return entries;
}

/**
 * The directory the `skills` CLI installs a skill into: its name sanitized as the CLI does it (`sanitizeName`), so
 * `model-redux-state/design-state-ownership` lives in `model-redux-state-design-state-ownership`.
 */
export const skillDirName = (name: string): string =>
    name
        .toLowerCase()
        .replace(/[^a-z0-9._]+/g, '-')
        .replace(/^[.-]+|[.-]+$/g, '')
        .slice(0, 255) || 'unnamed-skill';

/**
 * Directory names of the skills the `skills` CLI installed, from its `skills-lock.json` in cwd; empty when there is
 * none.
 */
export function readSyncedSkills(cwd: string): Set<string> {
    try {
        const lock: unknown = JSON.parse(fs.readFileSync(path.join(cwd, SKILLS_LOCK), 'utf-8'));
        const skills = (lock as { skills?: unknown })?.skills;
        return new Set(skills && typeof skills === 'object' ? Object.keys(skills).map(skillDirName) : []);
    } catch {
        return new Set();
    }
}

/**
 * A symlink into `node_modules`: how the `skills` CLI links a package skill, before its lock lists it.
 */
const isPackageLink = (entry: string): boolean =>
    !!lstat(entry)?.isSymbolicLink() && fs.readlinkSync(entry).split(/[\\/]/).includes('node_modules');

/**
 * The user's own top-level entries in `.agents/rules` and `.agents/skills`, keyed like packageEntries() - everything
 * there except the links this tool placed (its generated `.gitignore` lists them), the skills the `skills` CLI
 * installed, dead links and dotfiles.
 */
export function readUserEntries(cwd: string): Map<string, string> {
    const entries = new Map<string, string>();
    const synced = readSyncedSkills(cwd);

    for (const kind of AGENT_KINDS) {
        const root = path.join(cwd, CANONICAL_AGENT_DIR, kind);

        if (!fs.statSync(root, { throwIfNoEntry: false })?.isDirectory()) continue;

        const own = manifestNames(root);

        for (const name of fs.readdirSync(root)) {
            const entry = path.join(root, name);
            const isSynced = kind === 'skills' && (synced.has(name) || isPackageLink(entry));

            if (!name.startsWith('.') && !own.has(name) && !isSynced && fs.existsSync(entry))
                entries.set(path.join(kind, name), entry);
        }
    }

    return entries;
}

/**
 * Run the `skills` CLI this package depends on, in `cwd`, telemetry off unless the user set it. A failure is a
 * warning, the install goes on. Returns whether the command succeeded.
 */
function runSkillsCli(cwd: string, args: string[], run: RunCommand): boolean {
    const manifestPath = createRequire(import.meta.url).resolve('skills/package.json');
    const { bin } = JSON.parse(fs.readFileSync(manifestPath, 'utf-8')) as { bin: Record<string, string> };
    const result = run(process.execPath, [path.join(path.dirname(manifestPath), bin.skills), ...args], {
        cwd,
        stdio: 'inherit',
        env: { DISABLE_TELEMETRY: '1', ...process.env },
    });

    if (result.status === 0) return true;

    console.warn(
        `[lint-prepare] skills ${args[0]} failed (${result.error?.message ?? `exit code ${result.status}`}), skills may be missing: re-run lint-prepare`,
    );
    return false;
}

/**
 * Install the skills dependencies ship (this package's own `skills/` folder among them) with the `skills` CLI, into
 * `.agents/skills`, linked into `.claude/skills`. `exclude`: `package` or `package#skill` patterns to leave out. On CI
 * nothing remote is touched (`--no-remote`). Returns whether the sync succeeded.
 */
export function runSkillsSync(cwd: string, run: RunCommand = spawnSync, exclude: string[] = []): boolean {
    const args = [...SKILLS_SYNC_ARGS];

    if (process.env.CI) args.push('--no-remote');
    if (exclude.length) args.push('--exclude', ...exclude);

    return runSkillsCli(cwd, args, run);
}

/** An npm package that ships skills (`@scope/name`, or a name without `/`); anything else is a git source. */
export const isNpmSkillSource = (source: string): boolean => source.startsWith('@') || !source.includes('/');

/** A git source to install with `skills add`: the listed skills, or all of them (`*`) except `exclude`. */
export type RemoteSkills = { source: string; ref?: string; skills: string[] | '*'; exclude: string[] };

/** What `lint-prepare` does with the `skills` map of `lint.config.ts`. */
export type SkillsPlan = { syncExclude: string[]; remote: RemoteSkills[] };

/**
 * Names of the skills an installed npm package ships: `skills/<name>/SKILL.md` or `dist/skills/<name>/SKILL.md`.
 */
export function readPackageSkills(cwd: string, packageName: string): string[] {
    return ['skills', path.join('dist', 'skills')].flatMap((dir) => {
        const root = path.join(cwd, 'node_modules', packageName, dir);

        if (!fs.existsSync(root)) return [];

        return fs
            .readdirSync(root, { withFileTypes: true })
            .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(root, entry.name, 'SKILL.md')))
            .map((entry) => entry.name);
    });
}

/**
 * Turn the `skills` map into CLI work. npm sources become `experimental_sync` exclusions: a disabled package, the
 * `false` skills, or - when a package lists `true` skills - every other skill it ships. Enabled git sources become
 * `skills add` work.
 */
export function planSkills(
    skills: SkillsConfig,
    packageSkills: (packageName: string) => string[] = () => [],
): SkillsPlan {
    const plan: SkillsPlan = { syncExclude: [], remote: [] };

    for (const [source, option] of Object.entries(skills)) {
        const { enabled = true, ref, skills: names = {} } = asOptions(option);
        const listed = Object.keys(names).filter((name) => names[name]);
        const excluded = Object.keys(names).filter((name) => !names[name]);

        if (isNpmSkillSource(source)) {
            if (!enabled) plan.syncExclude.push(source);
            else {
                const left = listed.length ? packageSkills(source).filter((name) => !listed.includes(name)) : excluded;
                plan.syncExclude.push(...left.map((name) => `${source}#${name}`));
            }
            continue;
        }

        if (enabled) plan.remote.push({ source, ref, skills: listed.length ? listed : '*', exclude: excluded });
    }

    return plan;
}

type LockEntry = { source: string; ref?: string; sourceType?: string; via?: string };

/** The entries of `skills-lock.json` in cwd; empty when there is none. */
function readSkillsLock(cwd: string): Record<string, LockEntry> {
    try {
        const lock = JSON.parse(fs.readFileSync(path.join(cwd, SKILLS_LOCK), 'utf-8')) as { skills?: unknown };
        return lock.skills && typeof lock.skills === 'object' ? (lock.skills as Record<string, LockEntry>) : {};
    } catch {
        return {};
    }
}

/**
 * Install the git sources of the plan with `skills add`, skipping a source whose skills the lock already has at the
 * same ref, then remove what the plan no longer wants: `lint.config.ts` owns the remote skills of `skills-lock.json`
 * (the ones no package `skills` field asked for). Nothing on CI: remote skills need the network.
 */
export function syncRemoteSkills(cwd: string, remote: RemoteSkills[], run: RunCommand = spawnSync): void {
    if (process.env.CI) return;

    const own = (entry: LockEntry) => entry.sourceType !== 'node_modules' && !entry.via;
    const fromSource = (lock: Record<string, LockEntry>, { source, ref }: RemoteSkills) =>
        Object.keys(lock).filter((name) => own(lock[name]) && lock[name].source === source && lock[name].ref === ref);

    for (const wanted of remote) {
        const installed = fromSource(readSkillsLock(cwd), wanted);
        const complete =
            wanted.skills === '*' ? installed.length > 0 : wanted.skills.every((name) => installed.includes(name));

        if (complete) continue;

        const skills = wanted.skills === '*' ? ['*'] : wanted.skills;
        const source = wanted.ref ? `${wanted.source}#${wanted.ref}` : wanted.source;
        runSkillsCli(cwd, ['add', source, '-y', ...SKILLS_AGENTS, '--skill', ...skills], run);
    }

    const lock = readSkillsLock(cwd);
    const kept = new Set(
        remote.flatMap((wanted) =>
            fromSource(lock, wanted).filter((name) =>
                wanted.skills === '*' ? !wanted.exclude.includes(name) : wanted.skills.includes(name),
            ),
        ),
    );
    const stale = Object.keys(lock).filter((name) => own(lock[name]) && !kept.has(name));

    if (stale.length) runSkillsCli(cwd, ['remove', ...stale, '-y'], run);
}

/** Package rules the `rules` map of `lint.config.ts` keeps. */
export function enabledRules(rules: Rule[], config: LintConfig): Rule[] {
    return rules.filter((rule) => config.rules?.[rule.name] !== false);
}

/**
 * List the skills the `skills` CLI installed in the `.gitignore` of every agent `skills` dir: they stay out of git, and
 * the links this tool placed keep their own list.
 */
export function recordSyncedSkills(cwd: string): void {
    const synced = [...readSyncedSkills(cwd)];

    for (const dir of AGENT_DIRS) {
        const root = path.join(cwd, dir, 'skills');

        if (!lstat(root)?.isDirectory()) continue;

        const gitignore = path.join(root, GITIGNORE);
        writeManifest(
            gitignore,
            readManifest(gitignore),
            synced.filter((name) => lstat(path.join(root, name))),
        );
    }
}

/**
 * Make `rules` and `skills` real directories in every agent dir and link the top-level entries we know into them:
 * package rule files into both, pointing straight at the package, the user's own `.agents` entries into `.claude`.
 * A real entry is the user's - never written over or through. Dead links are removed, and so are links from the
 * previous run that are no longer placed (incl. the package skill links of older versions, so the `skills` CLI can
 * place its own): each directory's generated `.gitignore` records them (and keeps them out of git, so the user's own
 * entries there stay tracked); the skills the `skills` CLI installed are listed there too, but never cleaned up. The
 * `commands` directories older versions synced are cleaned up the same way, `.codex` is not touched.
 *
 * FIXME Codex Includes
 *   https://github.com/openai/codex/issues/17401
 *   https://github.com/openai/codex/issues/6038
 *   32kb limit https://github.com/openai/codex/issues/13386
 *
 * TODO: generate `.claude/CLAUDE.md` with an index of the symlinked rules, for humans browsing `.claude/rules` manually
 *   (Claude Code itself doesn't need it - it auto-loads every file under `.claude/rules` regardless of whether it's
 *   indexed anywhere).
 */
export function syncAgentDirs(
    cwd: string,
    packageEntries: Map<string, string>,
    userEntries: Map<string, string>,
): void {
    const links = plannedLinks(cwd, packageEntries, userEntries);

    for (const dir of LEGACY_DIRS) cleanUpLegacyDir(cwd, dir);

    for (const dir of AGENT_DIRS) {
        for (const kind of AGENT_KINDS) {
            const root = path.join(dir, kind);
            const rootPath = path.join(cwd, root);
            const gitignore = path.join(rootPath, GITIGNORE);
            const planned = [...links].filter(([link]) => path.dirname(link) === root);

            if (!ensureRealDir(cwd, root)) {
                console.log(`Skipped ${root}: not a real directory`);
                continue;
            }

            for (const link of findDeadLinks(rootPath)) {
                removeLink(link, rootPath);
            }

            // before placing: an older version's per-file links fill a real directory where a folder link goes now
            for (const link of readManifest(gitignore)) {
                const linkPath = path.join(rootPath, link);
                const isPlanned = planned.some(([plannedLink]) => plannedLink === path.join(root, link));
                if (!isPlanned && lstat(linkPath)?.isSymbolicLink()) removeLink(linkPath, rootPath);
            }

            const placed = planned
                .filter(([link, target]) => placeLink(cwd, link, target))
                .map(([link]) => path.relative(root, link));

            writeManifest(gitignore, placed, readGitignoreBlocks(gitignore).synced);
        }
    }
}

/**
 * Rules as they end up in `.agents/rules`: the package ones plus the user's own, which win on the same file.
 */
export function installedRules(rules: Rule[], userEntries: Map<string, string>): Rule[] {
    const byFile = new Map(rules.map((rule) => [rule.file, rule]));
    const rulesDir = `rules${path.sep}`;

    for (const [entry, source] of userEntries) {
        if (!entry.startsWith(rulesDir) || !entry.endsWith('.md') || !fs.statSync(source).isFile()) continue;

        const ruleFile = entry.slice(rulesDir.length);
        byFile.set(ruleFile, toRule(ruleFile, fs.readFileSync(source, 'utf-8')));
    }

    return [...byFile].sort(([a], [b]) => (a < b ? -1 : 1)).map(([, rule]) => rule);
}

/**
 * Fail if `CLAUDE.md` exists and isn't a symlink - we don't want to silently blow away a file the user wrote.
 */
export function checkClaudeMdSafety(claudeMdPath: string): void {
    let stat;

    try {
        stat = fs.lstatSync(claudeMdPath);
    } catch {
        return;
    }

    if (!stat.isSymbolicLink()) {
        console.error(`${CLAUDE_FILE} exists and is not a symlink.`);
        console.error('Remove or back it up manually, then re-run.');
        process.exit(1);
    }
}

/**
 * Symlink CLAUDE.md -> AGENTS.md so both point at the same generated content.
 */
export function symlinkClaudeMd(cwd: string): void {
    const claudeMdPath = path.join(cwd, CLAUDE_FILE);

    fs.rmSync(claudeMdPath, { force: true });
    fs.symlinkSync(AGENTS_FILE, claudeMdPath);
}

/**
 * Generate AGENTS.md with a `# Rules` section: one entry per rule (the package's and the user's own) with
 * its frontmatter `description`, the `paths` it is scoped to and a plain link to its `.agents/rules` entry.
 *
 * The links are plain, never `@path` imports: Claude Code loads `.claude/rules` itself (syncAgentDirs() links them
 * there) and honours each rule's `paths`, while an `@` import would load every rule into every session, scoped or not.
 * Codex, which expands no `@`, reads this index.
 */
export function generateAgentsFile(rules: Rule[], customSection: string | null, previous = ''): string {
    const entries = rules.map((rule) => {
        // the canonical entry (a package link or the user's own file), not the package install path
        const rulePath = `${CANONICAL_AGENT_DIR}/rules/${rule.file}`;
        const description = rule.description ? ` — ${rule.description}` : '';
        const scope = rule.paths ? `; when touching ${rule.paths.map((glob) => `\`${glob}\``).join(', ')}` : '';

        return `- **${toTitle(rule.name)}**${description}${scope}: [${rulePath}](${rulePath})`;
    });

    // what a tool wrote between its markers last time stays: lint-prepare never empties it
    const sections = TOOL_SECTIONS.map(({ start, end }) => {
        const from = previous.indexOf(start);
        const to = from === -1 ? -1 : previous.indexOf(end, from);
        return to === -1 ? `${start}\n${end}` : previous.slice(from, to + end.length);
    });
    const generated = `${HEADER}\n\n# Rules\n\n${entries.join('\n')}\n\n${sections.join('\n\n')}\n\n${FOOTER}\n\n${GENERATED_MARKER}`;

    return customSection ? `${generated}\n\n${customSection}\n` : `${generated}\n`;
}

/**
 * Check if AGENTS.md exists and was generated by this tool. When it was, also return
 * whatever follows the marker (the user's custom section) so it can be carried forward -
 * generateAgentsFile() always rebuilds the part above the marker from scratch, but must
 * never touch what a user wrote below it.
 */
export function checkExisting(targetPath: string): ExistingFile {
    if (!fs.existsSync(targetPath)) {
        return { exists: false, generated: false, customSection: null };
    }

    const content = fs.readFileSync(targetPath, 'utf-8');
    const markerIndex = content.indexOf(GENERATED_MARKER);
    const generated = markerIndex !== -1;
    const customSection = generated ? content.slice(markerIndex + GENERATED_MARKER.length).trim() : null;

    return { exists: true, generated, customSection };
}

/**
 * Main function
 */
export async function main(): Promise<void> {
    const args = process.argv.slice(2);
    const command = args[0] || 'init';
    const cwd = process.env.INIT_CWD || process.cwd();
    const targetPath = path.join(cwd, AGENTS_FILE);
    const claudeMdPath = path.join(cwd, CLAUDE_FILE);

    console.log(`@kirill.konshin/lint: ${command}`);
    console.log(`Target: ${targetPath}`);

    const { exists, generated, customSection } = checkExisting(targetPath);

    if (command === 'init') {
        if (exists && !generated) {
            console.log(`${AGENTS_FILE} exists and was not generated by this tool. Skipping.`);
            console.log('Use "lint-prepare update" to force overwrite, then merge manually.');
            return;
        }

        if (exists && generated) {
            console.log(`${AGENTS_FILE} exists and was generated by this tool. Updating...`);
        }
    }

    if (command === 'update' || command === 'init') {
        checkClaudeMdSafety(claudeMdPath);

        const root = findWorkspaceRoot(cwd);
        if (!fs.existsSync(path.join(root, LINT_CONFIG_FILE))) {
            console.warn(
                `[lint-prepare] ${LINT_CONFIG_FILE} is missing in ${root}: create it (see the @kirill.konshin/lint README), the defaults apply until then`,
            );
        }
        const config = await resolveLintConfig({}, root);
        const rules = enabledRules(readRules(), config);
        console.log(`Found ${rules.length} rule files: ${rules.map((r) => r.name).join(', ')}`);

        const userEntries = readUserEntries(cwd);
        syncAgentDirs(cwd, packageEntries(rules), userEntries);
        console.log(
            `Synced ${AGENT_DIRS.join(', ')}, mirrored ${userEntries.size} own entries from ${CANONICAL_AGENT_DIR}`,
        );

        // after syncAgentDirs(): it removes the skill links older versions placed, the CLI then places its own; the sync
        // first, it drops the skills a package `skills` field no longer asks for
        const plan = planSkills(config.skills ?? {}, (packageName) => readPackageSkills(cwd, packageName));
        if (runSkillsSync(cwd, spawnSync, plan.syncExclude))
            console.log(`Synced skills with the skills CLI, see ${SKILLS_LOCK}`);
        syncRemoteSkills(cwd, plan.remote);
        recordSyncedSkills(cwd);

        const previous = exists ? fs.readFileSync(targetPath, 'utf-8') : '';
        const content = generateAgentsFile(installedRules(rules, userEntries), customSection, previous);
        fs.writeFileSync(targetPath, content, 'utf-8');
        console.log(`${exists ? 'Updated' : 'Created'} ${AGENTS_FILE}`);

        symlinkClaudeMd(cwd);
        console.log(`Symlinked ${CLAUDE_FILE} -> ${AGENTS_FILE}`);
        return;
    }

    console.log(`Unknown command: ${command}`);
    console.log('Usage: lint-prepare [init|update]');
    process.exit(1);
}

// Only run when executed directly (e.g. `lint-prepare init`), not when imported.
if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(__filename)) {
    try {
        await main();
    } catch (error) {
        console.error(error);
        process.exit(1);
    }
}
