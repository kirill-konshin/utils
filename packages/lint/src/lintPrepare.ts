#!/usr/bin/env node

/**
 * @kirill.konshin/lint
 *
 * This script makes `rules` and `skills` real directories in the consuming project's `.agents`
 * (canonical, cross-tool, Codex reads it) and `.claude` (Claude Code), and symlinks the top-level
 * entries it knows into them: package rule files go into both, pointing straight at the installed
 * package; the user's own `.agents` entries are mirrored into `.claude`. Skills are installed by the `skills` CLI,
 * which this script runs: the skills dependencies ship (`skills experimental_sync`) and the git sources the `skills`
 * map of `lint.config.ts` lists (`skills add`). The `rules` map of `lint.config.ts` leaves package rules out. It also
 * generates an `AGENTS.md` file for other tools, with `CLAUDE.md` symlinked to `AGENTS.md`.
 *
 * Usage:
 *   lint-prepare init    - Initialize AGENTS.md in the current directory (default)
 *   lint-prepare update  - Force update AGENTS.md even if it exists
 *   lint-prepare         - Same as init
 *
 * The module also exports its functions and only runs `main()` when executed directly,
 * so it can be imported (for testing/reuse) without side effects.
 */

